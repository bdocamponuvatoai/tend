// Generates responsive AVIF/WebP versions of the hero photo, and the social
// share card, from the original JPEG. Run after replacing
// src/assets/images/hero-table.jpg:
//   npm run images
// Uses sharp, which ships with Next.js.
//
// WebP sizes are imported by the hero (src/assets/images/hero). AVIF sizes go
// to public/images/hero with a content hash in the name, listed in
// src/assets/images/hero/avif-sources.ts: Turbopack cannot import AVIF, and
// the hash lets vercel.json cache them as immutable.
import { createHash } from "node:crypto";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SOURCE = "src/assets/images/hero-table.jpg";
const OUT_DIR = "src/assets/images/hero";
const AVIF_DIR = "public/images/hero";
const AVIF_MANIFEST = path.join(OUT_DIR, "avif-sources.ts");
const WIDTHS = [640, 960, 1280, 1536];
const OG_IMAGE = "src/assets/images/og-image.jpg";

await mkdir(OUT_DIR, { recursive: true });
await mkdir(AVIF_DIR, { recursive: true });
// Remove previous hashed AVIF files so stale sizes don't linger.
for (const file of await readdir(AVIF_DIR)) {
  if (file.endsWith(".avif")) await rm(path.join(AVIF_DIR, file));
}

const avif = [];
for (const width of WIDTHS) {
  const base = sharp(SOURCE).resize({ width, withoutEnlargement: true });
  const avifBuffer = await base
    .clone()
    .avif({ quality: 55, effort: 6 })
    .toBuffer();
  const hash = createHash("sha256")
    .update(avifBuffer)
    .digest("hex")
    .slice(0, 10);
  const name = `hero-table-${width}-${hash}.avif`;
  await writeFile(path.join(AVIF_DIR, name), avifBuffer);
  avif.push({ src: `/images/hero/${name}`, width });
  await base
    .clone()
    .webp({ quality: 74, effort: 6 })
    .toFile(path.join(OUT_DIR, `hero-table-${width}.webp`));
}
await writeFile(
  AVIF_MANIFEST,
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
// AVIF sizes of the hero photo, served from public/images/hero with
// content-hashed names: Turbopack cannot import AVIF, and the hash lets
// vercel.json cache them as immutable.
export const HERO_AVIF = [
${avif.map((a) => `  { src: "${a.src}", width: ${a.width} },`).join("\n")}
] as const;
`,
);
console.log(
  `Wrote ${WIDTHS.length} WebP sizes to ${OUT_DIR}, ${WIDTHS.length} AVIF sizes to ${AVIF_DIR} and ${AVIF_MANIFEST}`,
);

// Social share card (Open Graph / Twitter): 1200×630, centre crop.
await sharp(SOURCE)
  .resize(1200, 630, { fit: "cover", position: "centre" })
  .jpeg({ quality: 80, mozjpeg: true })
  .toFile(OG_IMAGE);
console.log(`Wrote ${OG_IMAGE}`);
