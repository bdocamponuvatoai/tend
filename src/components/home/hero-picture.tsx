import type { StaticImageData } from "next/image";
import heroJpg from "@/assets/images/hero-table.jpg";
import avif640 from "@/assets/images/hero/hero-table-640.avif";
import avif960 from "@/assets/images/hero/hero-table-960.avif";
import avif1280 from "@/assets/images/hero/hero-table-1280.avif";
import avif1536 from "@/assets/images/hero/hero-table-1536.avif";
import webp640 from "@/assets/images/hero/hero-table-640.webp";
import webp960 from "@/assets/images/hero/hero-table-960.webp";
import webp1280 from "@/assets/images/hero/hero-table-1280.webp";
import webp1536 from "@/assets/images/hero/hero-table-1536.webp";

// Widths as generated by scripts/optimize-images.mjs. (Static imports of
// AVIF/WebP do not report their real dimensions, so they are listed here.)
const WIDTHS = [640, 960, 1280, 1536] as const;
const srcSet = (images: StaticImageData[]) =>
  images.map((image, i) => `${image.src} ${WIDTHS[i]}w`).join(", ");

// The photo is cropped to cover its box, so the width it is drawn at follows
// the box height: about 1.5 × the box height on every screen.
const SIZES = "(min-width: 1001px) 1240px, (min-width: 701px) 1100px, 150vw";

/**
 * Hero photo as AVIF/WebP at four widths (generated by `npm run images`), with
 * the original JPEG as the fallback. It is the largest image above the fold,
 * so it loads eagerly at high priority.
 */
export function HeroPicture({ alt }: { alt: string }) {
  return (
    <picture>
      <source
        type="image/avif"
        srcSet={srcSet([avif640, avif960, avif1280, avif1536])}
        sizes={SIZES}
      />
      <source
        type="image/webp"
        srcSet={srcSet([webp640, webp960, webp1280, webp1536])}
        sizes={SIZES}
      />
      <img
        src={heroJpg.src}
        width={heroJpg.width}
        height={heroJpg.height}
        alt={alt}
        loading="eager"
        fetchPriority="high"
        decoding="async"
      />
    </picture>
  );
}
